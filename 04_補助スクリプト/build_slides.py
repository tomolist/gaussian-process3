def thick_table(mat, x, y, w, size=18):
    """B_Tff の厚みごとの表（厚み、比 R の実測・予測、ずれの換算前→換算後、判定）。返り値：下端"""
    c = check_rows(mat)
    rows = [["厚み\n(mm)", "比 R\n実測", "比 R\n予測", "換算前後\nのずれ", "判定"]]
    for _, r in c.iterrows():
        rows.append([f"{r['厚み']:.1f}", f"{r['R_実測']:.2f}", f"{r['R_予測']:.2f}", f"{pe(r['ずれ_換算前']):.1f} → {pe(r['ずれ_換算後']):.1f}%",
                     f"[b][s=22]{r['判定']}[/s][/b]"])
    ws = [w * f for f in (0.18, 0.17, 0.17, 0.32, 0.16)]
    return D.table(x, y, ws, rows, size, row_h=16.0, head_fill=NAVY, fills=("FFFFFF", LIGHT), aligns=["center"] * 5)


def thick_verdict(mat):
    """B_Tff の厚みごとの判定から、結論の一文を作る"""
    c = check_rows(mat)
    ok = c[c["判定"] == "○"]["厚み"].tolist()
    ng = c[c["判定"] != "○"]
    s = "すべての厚みで ○" if len(ng) == 0 else f"{'・'.join(f'{h:.1f}' for h in ok)} mm は ○" if ok else "○ の厚みはない"
    reasons = []
    for _, r in ng.iterrows():
        why = []
        if not r["順序が一致"]:
            why.append("温度の順序が実測と逆")
        if not r["比の大きさが一致"]:
            why.append(f"比 R が実測 {r['R_実測']:.2f}・予測 {r['R_予測']:.2f} とずれる")
        if not r["換算でずれが減る"]:
            why.append("換算でずれが減らない")
        reasons.append(f"{r['厚み']:.1f} mm は {r['判定']}（{'、'.join(why)}）")
    return s + ("。" + "。".join(reasons) if reasons else "：温度の順序・比の大きさ・換算後のずれの 3 つとも、温度シフトファクターが効いている")


