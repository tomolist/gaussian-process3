def temp_verdict(mat):
    """シフトに使う温度の判定（厚みごと）から、結論の一文を作る"""
    s = win_rows(mat)
    over = s["総合の判定"]
    if (over == "差なし").all():
        head = "多数決では、すべての厚みで差なし"
    else:
        head = "多数決では、" + "、".join(f"{h_list(s[over == k]['厚み'])} は{WIN_JA[k]}" for k in ["Tff", "Tset", "差なし"] if (over == k).any())
    parts = []
    for c, lab in [("a", "重ね合わせ"), ("b", "対数周辺尤度"), ("c", "予測誤差")]:
        for k in ["Tff", "Tset"]:
            hs = s[s[f"適した温度({c})"] == k]["厚み"]
            if len(hs):
                parts.append(f"({c}) {lab}では {h_list(hs)} で{WIN_JA[k]}")
    return head + ("。" + "、".join(parts) + "が適した" if parts else "。3 つの基準とも、すべての厚みで差なし")


