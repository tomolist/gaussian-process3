def r_(mat, sp, k, sub):
    return rmse(M(mat, sp, k, sub))


def ratio_rng(mat, k, split="S_V"):
    e = eff[(eff["material"] == MAT[mat]) & (eff["split"] == split) & (eff["model"] == k)]["ratio_190_230"]
    return f"{e.min():.2f}〜{e.max():.2f}"


def obs_rng(mat):
    o = obs[obs["material"] == MAT[mat]]["observed"]
    return f"{o.min():.2f}〜{o.max():.2f}"


def max_dev(mat, k):
    e = eff[(eff["material"] == MAT[mat]) & (eff["split"] == "S_V") & (eff["model"] == k)].sort_values("H")["ratio_190_230"].to_numpy()
    o = obs[obs["material"] == MAT[mat]].sort_values("H")["observed"].to_numpy()
    return float(np.abs(e - o).max())


def lo_noise(mat, k):
    return K(mat, k, "noise_sd")


def bad_ls(mat):
    kk = ker[(ker["material"] == MAT[mat]) & (ker["data"] == "なし") & ker["model"].isin(TSET) & (ker["ls_Tset"] < 0.05)]
    return sorted(set(kk["split"] + "：" + kk["model"]))


